ALTER TABLE leave_request ADD COLUMN IF NOT EXISTS start_time TIMESTAMP;
ALTER TABLE leave_request ADD COLUMN IF NOT EXISTS end_time TIMESTAMP;
CREATE TABLE IF NOT EXISTS attendance_audit (
 id VARCHAR(36) PRIMARY KEY, category VARCHAR(40) NOT NULL, entity_id BIGINT NOT NULL,
 before_status VARCHAR(30), after_status VARCHAR(30), operator_id BIGINT NOT NULL,
 reason VARCHAR(500), created_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS face_reenroll_request (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student_id BIGINT NOT NULL,
 reason VARCHAR(500), status VARCHAR(20) DEFAULT 'PENDING', reviewer_id BIGINT,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, reviewed_at TIMESTAMP
);
